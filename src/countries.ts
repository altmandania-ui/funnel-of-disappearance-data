export function normalizeCountryName(name: string): string {
  return name
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[\u2019'.-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

const BY_M49 = new Map<number, { iso3: string; name: string }>();
const BY_NAME = new Map<string, string>();
const NAME_BY_ISO3 = new Map<string, string>();
for (const [m49, iso3, name] of COUNTRY_TABLE) {
  BY_M49.set(m49, { iso3, name });
  BY_NAME.set(normalizeCountryName(name), iso3);
  NAME_BY_ISO3.set(iso3, name);
}
for (const [alias, iso3] of Object.entries(ALIASES)) BY_NAME.set(normalizeCountryName(alias), iso3);

export function m49ToIso3(code: string | number): string | null {
  return BY_M49.get(Number(code))?.iso3 ?? null;
}

export function nameToIso3(name: string | null | undefined): string | null {
  if (!name) return null;
  return BY_NAME.get(normalizeCountryName(name)) ?? null;
}

export function iso3ToName(iso3: string): string | null {
  return NAME_BY_ISO3.get(iso3) ?? null;
}
